export function getGoodDeityCard(id?: number): GoodDeityCard {
  if (id && id >= 1 && id <= GOOD_DEITY_CARDS.length) {
    return GOOD_DEITY_CARDS[id - 1];
  }
  const index = Math.floor(Math.random() * GOOD_DEITY_CARDS.length);
  return GOOD_DEITY_CARDS[index];
}
