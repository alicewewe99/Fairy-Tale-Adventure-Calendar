// Helper to pick oracle
export function getZhenhaiOracle(signNo?: number): ZhenhaiOracle {
  if (signNo && signNo >= 1 && signNo <= ZHENHAI_ORACLES.length) {
    return ZHENHAI_ORACLES[signNo - 1];
  }
  const randomIndex = Math.floor(Math.random() * ZHENHAI_ORACLES.length);
  return ZHENHAI_ORACLES[randomIndex];
}
