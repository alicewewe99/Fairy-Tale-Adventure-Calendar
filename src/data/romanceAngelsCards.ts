export function getRomanceAngelCard(id?: number): RomanceAngelCard {
  if (id && id >= 1 && id <= ROMANCE_ANGELS_CARDS.length) {
    return ROMANCE_ANGELS_CARDS[id - 1];
  }
  const index = Math.floor(Math.random() * ROMANCE_ANGELS_CARDS.length);
  return ROMANCE_ANGELS_CARDS[index];
}
